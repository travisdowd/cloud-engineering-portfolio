# Python Basics - Exercise 3: Lists and Dictionaries

# Create a list of favorite fruits
favorite_fruits = ["Apples", "Bananas", "Strawberries", "Oranges"]

# Create a dictionary with key-value pairs
cloud_skills = {
    "language": "Python",
    "platform": "AWS",
    "purpose": "Cloud Engineering"
}

# Print the list
print("Favorite Fruits:")
for fruit in favorite_fruits:
    print(fruit)

# Print the dictionary
print("\nCloud Skills:")
for key, value in cloud_skills.items():
    print(key, ":", value)

